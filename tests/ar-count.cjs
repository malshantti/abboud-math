const A=require('../ar-count.js'),assert=require('assert');
const eq=(n,w,exp,o)=>assert.strictEqual(A(n,w,o),exp,`${n} ${w}`);
eq(1,'يوم','1 يوم');eq(2,'يوم','2 يومان');eq(2,'يوم','2 يومين',{case:'o'});eq(3,'يوم','3 أيام');eq(10,'يوم','10 أيام');eq(11,'يوم','11 يومًا');eq(25,'يوم','25 يومًا');eq(99,'يوم','99 يومًا');
eq(100,'يوم','100 يوم');eq(200,'دينار','200 دينار');eq(101,'دينار','101 دينار');eq(103,'دينار','103 دنانير');eq(115,'دينار','115 دينارًا');eq(1000,'شيكل','1000 شيكل');
eq(2,'ساعة','2 ساعتان');eq(5,'ساعة','5 ساعات');eq(12,'ساعة','12 ساعةً');eq(1,'وحدة','1 وحدة');eq(7,'وحدة','7 وحدات');eq(30,'وحدة','30 وحدةً');
eq(8,'شيكل','8 شواكل');eq(15,'شيكل','15 شيكلًا');eq(6,'سؤال','6 أسئلة');eq(10,'دقيقة','10 دقائق');eq(2.5,'ساعة','2.5 ساعة');eq(0,'وحدة','0 وحدة');
eq(6,'سؤال','٦ أسئلة',{fmt:n=>String(n).replace(/\d/g,d=>'٠١٢٣٤٥٦٧٨٩'[d])});
// negatives: wrong forms must not appear
for(const [n,w,bad] of [[10,'يوم','يومًا'],[2,'ساعة','ساعات'],[1,'وحدة','وحدات'],[8,'شيكل','شيكلًا'],[11,'يوم','أيام'],[100,'يوم','أيام'],[3,'دينار','دينارًا']])assert.ok(!A(n,w).endsWith(' '+bad),`${n} ${w} must not be ${bad}`);
assert.throws(()=>A(3,'جمل'));
// every noun has 5 non-empty forms
for(const [k,f] of Object.entries(A.nouns))assert.ok(f.length===5&&f.every(Boolean),k);
console.log('ar-count ok');
